#pragma once
#include <stdint.h>

// SX1262 command opcodes and constants for FSK mode
// Reference: Semtech SX1261/1262 datasheet, DS.SX1261-2.W.APP, Rev 2.1

// --- Operational mode commands ---
#define SX1262_CMD_SET_SLEEP 0x84
#define SX1262_CMD_SET_STANDBY 0x80
#define SX1262_CMD_SET_FS 0xC1
#define SX1262_CMD_SET_TX 0x83
#define SX1262_CMD_SET_RX 0x82
#define SX1262_CMD_STOP_TIMER_ON_PREAMBLE 0x9F
#define SX1262_CMD_SET_CAD 0xC5
#define SX1262_CMD_SET_TX_CONTINUOUS 0xD1
#define SX1262_CMD_SET_TX_INFINITE_PREAMBLE 0xD2
#define SX1262_CMD_SET_REGULATOR_MODE 0x96
#define SX1262_CMD_CALIBRATE 0x89
#define SX1262_CMD_CALIBRATE_IMAGE 0x98
#define SX1262_CMD_SET_PA_CONFIG 0x95
#define SX1262_CMD_SET_RX_TX_FALLBACK_MODE 0x93

// --- Register and buffer access ---
#define SX1262_CMD_WRITE_REGISTER 0x0D
#define SX1262_CMD_READ_REGISTER 0x1D
#define SX1262_CMD_WRITE_BUFFER 0x0E
#define SX1262_CMD_READ_BUFFER 0x1E

// --- DIO and IRQ commands ---
#define SX1262_CMD_SET_DIO_IRQ_PARAMS 0x08
#define SX1262_CMD_GET_IRQ_STATUS 0x12
#define SX1262_CMD_CLEAR_IRQ_STATUS 0x02
#define SX1262_CMD_SET_DIO2_AS_RF_SWITCH 0x9D
#define SX1262_CMD_SET_DIO3_AS_TCXO_CTRL 0x97

// --- RF modulation and packet commands ---
#define SX1262_CMD_SET_RF_FREQUENCY 0x86
#define SX1262_CMD_SET_PACKET_TYPE 0x8A
#define SX1262_CMD_GET_PACKET_TYPE 0x11
#define SX1262_CMD_SET_TX_PARAMS 0x8E
#define SX1262_CMD_SET_MODULATION_PARAMS 0x8B
#define SX1262_CMD_SET_PACKET_PARAMS 0x8C
#define SX1262_CMD_SET_BUFFER_BASE_ADDR 0x8F
#define SX1262_CMD_SET_SYNC_WORD 0x06 // via register write

// --- Status commands ---
#define SX1262_CMD_GET_STATUS 0xC0
#define SX1262_CMD_GET_RX_BUFFER_STATUS 0x13
#define SX1262_CMD_GET_PACKET_STATUS 0x14
#define SX1262_CMD_GET_RSSI_INST 0x15
#define SX1262_CMD_GET_STATS 0x10
#define SX1262_CMD_RESET_STATS 0x00
#define SX1262_CMD_GET_DEVICE_ERRORS 0x17
#define SX1262_CMD_CLEAR_DEVICE_ERRORS 0x07

// --- Standby modes ---
#define SX1262_STDBY_RC 0x00
#define SX1262_STDBY_XOSC 0x01

// --- RX/TX fallback modes ---
#define SX1262_FALLBACK_FS 0x40
#define SX1262_FALLBACK_STDBY_XOSC 0x30
#define SX1262_FALLBACK_STDBY_RC 0x20

// --- Packet types ---
#define SX1262_PACKET_TYPE_GFSK 0x00
#define SX1262_PACKET_TYPE_LORA 0x01

// --- Regulator modes ---
#define SX1262_REGULATOR_LDO 0x00
#define SX1262_REGULATOR_DC_DC 0x01

// --- IRQ bitmasks ---
#define SX1262_IRQ_TX_DONE (1 << 0)
#define SX1262_IRQ_RX_DONE (1 << 1)
#define SX1262_IRQ_PREAMBLE_DETECTED (1 << 2)
#define SX1262_IRQ_SYNC_WORD_VALID (1 << 3)
#define SX1262_IRQ_HEADER_VALID (1 << 4)
#define SX1262_IRQ_HEADER_ERR (1 << 5)
#define SX1262_IRQ_CRC_ERR (1 << 6)
#define SX1262_IRQ_CAD_DONE (1 << 7)
#define SX1262_IRQ_CAD_DETECTED (1 << 8)
#define SX1262_IRQ_TIMEOUT (1 << 9)
#define SX1262_IRQ_ALL 0x03FF

// --- PA configuration (SX1262 high-power) ---
#define SX1262_PA_DUTY_CYCLE_14DBM 0x02
#define SX1262_PA_HP_MAX_14DBM 0x02
#define SX1262_PA_DUTY_CYCLE_17DBM 0x02
#define SX1262_PA_HP_MAX_17DBM 0x03
#define SX1262_PA_DUTY_CYCLE_20DBM 0x03
#define SX1262_PA_HP_MAX_20DBM 0x05
#define SX1262_PA_DUTY_CYCLE_22DBM 0x04
#define SX1262_PA_HP_MAX_22DBM 0x07
#define SX1262_PA_DEVICE_SEL_SX1262 0x00
#define SX1262_PA_LUT_STANDARD 0x01

// --- PA ramp values (CMD_SET_TX_PARAMS) ---
#define SX1262_PA_RAMP_10U 0x00
#define SX1262_PA_RAMP_20U 0x01
#define SX1262_PA_RAMP_40U 0x02
#define SX1262_PA_RAMP_80U 0x03
#define SX1262_PA_RAMP_200U 0x04
#define SX1262_PA_RAMP_800U 0x05
#define SX1262_PA_RAMP_1700U 0x06
#define SX1262_PA_RAMP_3400U 0x07

// --- Calibration bitmasks ---
#define SX1262_CALIBRATE_RC64K (1 << 0)
#define SX1262_CALIBRATE_RC13M (1 << 1)
#define SX1262_CALIBRATE_PLL (1 << 2)
#define SX1262_CALIBRATE_ADC_PULSE (1 << 3)
#define SX1262_CALIBRATE_ADC_BULK_N (1 << 4)
#define SX1262_CALIBRATE_ADC_BULK_P (1 << 5)
#define SX1262_CALIBRATE_IMAGE (1 << 6)
#define SX1262_CALIBRATE_ALL 0x7F

// --- Device error flags (CMD_GET_DEVICE_ERRORS) ---
#define SX1262_DEVICE_ERROR_RC64K_CALIB 0x0001
#define SX1262_DEVICE_ERROR_RC13M_CALIB 0x0002
#define SX1262_DEVICE_ERROR_PLL_CALIB 0x0004
#define SX1262_DEVICE_ERROR_ADC_CALIB 0x0008
#define SX1262_DEVICE_ERROR_IMAGE_CALIB 0x0010
#define SX1262_DEVICE_ERROR_XOSC_START 0x0020
#define SX1262_DEVICE_ERROR_PLL_LOCK 0x0040
#define SX1262_DEVICE_ERROR_PA_RAMP 0x0100

// --- Key register addresses (16-bit) ---
#define SX1262_REG_SYNC_WORD_0 0x06C0
#define SX1262_REG_SYNC_WORD_1 0x06C1
#define SX1262_REG_SYNC_WORD_2 0x06C2
#define SX1262_REG_SYNC_WORD_3 0x06C3
#define SX1262_REG_SYNC_WORD_4 0x06C4
#define SX1262_REG_SYNC_WORD_5 0x06C5
#define SX1262_REG_SYNC_WORD_6 0x06C6
#define SX1262_REG_SYNC_WORD_7 0x06C7
#define SX1262_REG_NODE_ADDR 0x06CD
#define SX1262_REG_BROADCAST_ADDR 0x06CE
#define SX1262_REG_CRC_INIT_MSB 0x06BC
#define SX1262_REG_CRC_INIT_LSB 0x06BD
#define SX1262_REG_CRC_POLY_MSB 0x06BE
#define SX1262_REG_CRC_POLY_LSB 0x06BF
#define SX1262_REG_WHITENING_INIT_MSB 0x06B8
#define SX1262_REG_WHITENING_INIT_LSB 0x06B9
#define SX1262_REG_RX_GAIN 0x08AC
#define SX1262_REG_TX_CLAMP_CFG 0x08D8
#define SX1262_REG_OCP 0x08E7
#define SX1262_REG_XTA_TRIM 0x0911
#define SX1262_REG_XTB_TRIM 0x0912

// --- RX gain values ---
#define SX1262_RX_GAIN_POWER_SAVING 0x94
#define SX1262_RX_GAIN_BOOSTED 0x96

// --- Image calibration frequency ranges (for 868 MHz) ---
#define SX1262_IMAGE_CAL_FREQ1_868 0xD7
#define SX1262_IMAGE_CAL_FREQ2_868 0xDB
